//variables and data types

#include <stdio.h>

int main() {
    //declare variables
    float height;//%f
    double balance;//%lf
    int phone;//%d    
        
        
        
    printf("Enter height in mm or cm\t");
    scanf("%f", &height);
    
    printf("Enter balance\t");
    scanf("%lf",&balance);
    
    printf("Enter phone number\t");
    scanf("%d",&phone);
    
    
    printf("The height is %f\n",height);
    printf("The balance is %lf\n",balance);
    printf("phone number is %d",phone);
   
    
}
    
    
